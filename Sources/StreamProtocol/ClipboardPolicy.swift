import Foundation

/// The clipboard's rules, both ends (kind 32, docs/clipboard-plan.md): what a device's message asks
/// of the host, which change of the Mac's pasteboard the host sends and to whom, when a device
/// subscribes and stops, which text from the Mac a device writes, when the device offers its own
/// clipboard to the Mac (the chip), and every word. Pure (Foundation only): the host (HostClipboard)
/// and the device (StreamClient+Clipboard) do only what reads and writes a pasteboard, and
/// Tests/checks/clipboard checks this file with StreamProtocol's sources.
public enum ClipboardPolicy {
    /// `WindowList.clipboard` from a host that takes and sends text.
    public static let generation = 1
    /// The most a kind 32's JSON may be, either way (Clipboard.maxTextBytes says why).
    public static let maxPayload = StreamMessage.maxClientPayload
    /// A device's kind 32s a second, per connection: a tap sends one. More is a runaway or hostile
    /// client, and each could replace the Mac's clipboard.
    public static let perSecond = 4
    /// How often the host looks at its pasteboard's change count while a device subscribes.
    public static let lookInterval = 0.25
    /// How long the Mac's text stays on the device's clipboard.
    public static let deviceExpiry = 600.0
    /// How long the chip stays at most.
    public static let chipLifetime = 20.0
    /// A session whose first list comes this soon after Sill became active still gets that look: an
    /// app switch long enough for the Mac to evict the suspended device brings a reconnect first.
    public static let activationWindow = 15.0
    /// How long "Sent to…" or "Too long…" stays.
    public static let noteLifetime = 3.0

    // MARK: The wire

    /// A kind 32 that sets the other side's clipboard to `text`: its JSON, or nil when the text is
    /// empty, longer than `Clipboard.maxTextBytes`, or its JSON longer than `maxPayload`.
    public static func payload(text: String) -> Data? {
        guard !text.isEmpty, text.utf8.count <= Clipboard.maxTextBytes else { return nil }
        let data = Wire.encode(Clipboard(text: text))
        guard !data.isEmpty, data.count <= maxPayload else { return nil }
        return data
    }

    /// A device's subscription: `{}`.
    public static var subscription: Data { Wire.encode(Clipboard()) }
    /// A device's switch going off: `{"stop":true}`.
    public static var stopping: Data { Wire.encode(Clipboard(stop: true)) }

    // MARK: The host

    /// Password managers mark the passwords and codes they copy as concealed, and apps mark what
    /// they put on the clipboard only for a moment as transient (nspasteboard.org; 1Password,
    /// Bitwarden, KeePassXC, Strongbox). Never sent, never even read.
    public static let concealedType = "org.nspasteboard.ConcealedType"
    public static let transientType = "org.nspasteboard.TransientType"
    /// Those two, and the three older markers clipboard managers skip too: content an app made
    /// rather than the person copied, the older transient convention, and 1Password's own.
    public static let markerTypes = [concealedType, transientType, "org.nspasteboard.AutoGeneratedType",
                                     "de.petermaurer.TransientPasteboardType", "com.agilebits.onepassword"]
    /// What came to the Mac from another of the person's devices through Universal Clipboard. Not
    /// sent: reading it would fetch it from that device (macOS shows that it is pasting from it) for
    /// every copy made there, and those devices have it already.
    public static let remoteClipboardType = "com.apple.is-remote-clipboard"
    /// On every item the host writes from a device's text, its value the host's launch ID
    /// (`WindowList.launchID`): this launch's own write is never sent back out.
    public static let ownType = "me.saffer.sill.clipboard"

    public enum HostSkip: String, Equatable, Sendable {
        /// A password manager's or another app's marker (`markerTypes`).
        case marked
        /// From another of the person's devices through Universal Clipboard (`remoteClipboardType`).
        case remote
        /// What this host wrote itself from a device's text.
        case own
        /// No text (an image, a file without a name as text).
        case noText
        /// Empty text.
        case empty
        /// Longer than `Clipboard.maxTextBytes`, or its JSON longer than `maxPayload`.
        case tooLong
    }

    public enum HostDecision: Equatable, Sendable {
        /// To every subscriber, this kind 32.
        case send(Data)
        case skip(HostSkip)
    }

    /// A change of the Mac's pasteboard (`changeCount`, its items' `types`): whether the host sends
    /// it. Its own write first (`ownChangeCount`, the count after it; or its marker naming this
    /// launch), then the markers and Universal Clipboard's, from the types alone, so neither a
    /// password manager's data nor another device's is ever read; only then the text (`text`), and the
    /// marker's value (`ownMarker`) only when its type is there.
    public static func hostDecides(types: [String], changeCount: Int, ownChangeCount: Int?, launchID: String,
                                   ownMarker: () -> String?, text: () -> String?) -> HostDecision {
        if let own = ownChangeCount, own == changeCount { return .skip(.own) }
        if types.contains(where: { markerTypes.contains($0) }) { return .skip(.marked) }
        if types.contains(remoteClipboardType) { return .skip(.remote) }
        if types.contains(ownType), ownMarker() == launchID { return .skip(.own) }
        guard let text = text() else { return .skip(.noText) }
        guard !text.isEmpty else { return .skip(.empty) }
        guard let data = payload(text: text) else { return .skip(.tooLong) }
        return .send(data)
    }

    public enum Refusal: String, Equatable, Sendable {
        /// Not a Clipboard's JSON.
        case undecodable
        /// Text longer than `Clipboard.maxTextBytes` (a device of this change never sends it).
        case tooLong
    }

    /// What a device's kind 32 asks of the host.
    public enum FromDevice: Equatable, Sendable {
        /// Send this connection the Mac's copies from now on.
        case subscribe
        /// The same, and this text becomes the Mac's clipboard (and goes to every other subscriber).
        case set(String)
        /// Send this connection nothing more.
        case stop
        /// Nothing: not subscribed, nothing set.
        case refuse(Refusal)
    }

    /// `stop` wins over anything with it; text that is not empty sets; anything else (`{}`, empty
    /// text, an image alone, which this generation does not take) subscribes.
    public static func fromDevice(_ payload: Data) -> FromDevice {
        guard let clip = Wire.decode(Clipboard.self, from: payload) else { return .refuse(.undecodable) }
        if clip.stop == true { return .stop }
        guard let text = clip.text, !text.isEmpty else { return .subscribe }
        guard text.utf8.count <= Clipboard.maxTextBytes else { return .refuse(.tooLong) }
        return .set(text)
    }

    /// Who a device's text goes to: every subscriber but the one that sent it, in the order given.
    public static func forward<ID: Equatable>(to subscribers: [ID], from sender: ID) -> [ID] {
        subscribers.filter { $0 != sender }
    }

    /// A connection's kind 32 at `now`, after `arrivals` (the times of its earlier ones): whether it
    /// is taken, at most `perSecond` in any second, and the arrivals to keep (the last second's,
    /// with this one when taken).
    public static func admits(arrivals: [Double], now: Double) -> (taken: Bool, kept: [Double]) {
        let recent = arrivals.filter { now - $0 < 1 }
        guard recent.count < perSecond else { return (false, recent) }
        return (true, recent + [now])
    }

    // MARK: The device

    /// Whether the Mac's list says it takes and sends the clipboard.
    public static func hostTakes(_ hostClipboard: Int?) -> Bool { (hostClipboard ?? 0) >= generation }

    public enum Subscription: Equatable, Sendable {
        /// Send `subscription` now.
        case subscribe
        /// Send `stopping` now.
        case stop
        case none
    }

    /// The device's subscription on its connection: subscribe while the Mac takes the clipboard, the
    /// switch is on and this connection has not; stop when it has and the switch went off. A Mac
    /// that stopped saying it (its Share clipboard with devices turned off) forgot every
    /// subscription, so the connection has none, and subscribes again when it says it again.
    /// Returns what to send and whether the connection is subscribed after it.
    public static func deviceSubscription(hostClipboard: Int?, switchOn: Bool, subscribed: Bool)
        -> (send: Subscription, subscribed: Bool) {
        guard hostTakes(hostClipboard) else { return (.none, false) }
        if switchOn && !subscribed { return (.subscribe, true) }
        if !switchOn && subscribed { return (.stop, false) }
        return (.none, subscribed)
    }

    /// What this device sent last, and its clipboard's change count right after.
    public struct Sent: Equatable, Sendable {
        public var text: String
        public var changeCount: Int
        public init(text: String, changeCount: Int) { self.text = text; self.changeCount = changeCount }
    }

    /// A kind 32 from the Mac: the text the device writes to its clipboard, or nil. Only with the
    /// switch on, from a Mac that takes the clipboard, text not empty and within the cap, and never
    /// the text this device sent while its clipboard still holds it (its change count unchanged
    /// since the send: the Mac's echo, which a host of this generation never sends).
    public static func deviceWrites(_ payload: Data, switchOn: Bool, hostClipboard: Int?, lastSent: Sent?,
                                    changeCount: Int) -> String? {
        guard switchOn, hostTakes(hostClipboard), let clip = Wire.decode(Clipboard.self, from: payload),
              let text = clip.text, !text.isEmpty, text.utf8.count <= Clipboard.maxTextBytes else { return nil }
        if let lastSent, lastSent.text == text, lastSent.changeCount == changeCount { return nil }
        return text
    }

    /// The chip, "Paste on ‹Mac›": while connected to a Mac that takes the clipboard with the switch
    /// on, when the device's clipboard has text (`hasStrings`, which never asks to paste) and its
    /// change count is not the one Sill last handled (`handled`: sent, written from the Mac, or the
    /// chip dismissed or timed out for it). Asked when Sill becomes active, and at a session's start
    /// soon after (`looksAtSessionStart`).
    public static func offersChip(connected: Bool, hostClipboard: Int?, switchOn: Bool, hasStrings: Bool,
                                  changeCount: Int, handled: Int?) -> Bool {
        connected && hostTakes(hostClipboard) && switchOn && hasStrings && changeCount != handled
    }

    /// A session's first list that says the Mac takes the clipboard, at `now`: whether Sill's
    /// activation (`activatedAt`, nil for none yet) owes it the chip's look.
    public static func looksAtSessionStart(activatedAt: Double?, now: Double) -> Bool {
        guard let activatedAt else { return false }
        return now >= activatedAt && now - activatedAt <= activationWindow
    }

    public enum DeviceSend: Equatable, Sendable {
        case send(Data)
        /// The text is longer than the cap: nothing sent, the person told.
        case tooLong
        /// Nothing to send (no text, not connected, the Mac does not take it, the switch off).
        case nothing
    }

    /// What the system's Paste control gave (`strings`, one per item): the first that is not empty
    /// goes, as kind 32, to a connected Mac that takes the clipboard while the switch is on.
    public static func deviceSends(_ strings: [String], connected: Bool, hostClipboard: Int?, switchOn: Bool) -> DeviceSend {
        guard connected, hostTakes(hostClipboard), switchOn, let text = strings.first(where: { !$0.isEmpty }) else { return .nothing }
        guard let data = payload(text: text) else { return .tooLong }
        return .send(data)
    }

    /// Where the chip goes on the stream panel: under the bar at its top trailing corner sideways, and
    /// at its bottom corner while the link's line holds the top; held upright, at the picture's bottom
    /// trailing corner, just above the window bar or row 1 (the bar is under the picture there).
    public enum Corner: Equatable, Sendable { case topTrailing, bottomTrailing }
    public static func chipCorner(landscape: Bool, linkLineShown: Bool) -> Corner {
        landscape && !linkLineShown ? .topTrailing : .bottomTrailing
    }

    // MARK: Words

    public enum Copy {
        /// "256 KB".
        public static var cap: String { "\(Clipboard.maxTextBytes / 1024) KB" }

        // The chip.
        public static func chipTitle(mac: String) -> String { "Paste on \(mac)" }
        public static let chipSubtitle = "Then press ⌘V there."
        /// The chip's words for VoiceOver, one element; its Paste button and Dismiss are their own.
        public static func chipSpoken(mac: String, device: String) -> String {
            "Paste on \(mac). Sends the text you copied on this \(device) to \(mac)’s clipboard. Then press Command-V there."
        }
        public static let dismiss = "Dismiss"
        /// The Paste button's hint, on the chip and in Settings.
        public static func pasteHint(mac: String, device: String) -> String {
            "Sends the text you copied on this \(device) to \(mac)’s clipboard."
        }
        public static func sent(mac: String) -> String { "Sent to \(mac)’s clipboard. Press ⌘V there." }
        public static func sentSpoken(mac: String) -> String { "Sent to \(mac)’s clipboard. Press Command-V there." }
        public static func tooLong(mac: String) -> String { "Too long to send: \(mac) takes up to \(cap) of text." }

        // The Settings panel's This iPad group.
        public static let switchTitle = "Share Clipboard"
        public static func rowTitle(mac: String) -> String { "Paste on \(mac)" }
        public static func footnote(on: Bool, mac: String, device: String) -> String {
            on ? "Text you copy on \(mac) is ready to paste on this \(device). To paste on \(mac), copy text here, tap Paste, then press ⌘V there."
               : "Nothing you copy goes between this \(device) and \(mac) while this is off."
        }

        // The host's lines: one when a device subscribes or stops, never one per copy, never what
        // was copied.
        public static func sharesLine(device: String) -> String { "Clipboard: \(device) shares the clipboard." }
        public static func stoppedLine(device: String) -> String { "Clipboard: \(device) stopped sharing the clipboard." }
        /// One line a minute for what was ignored (RefusalSummary's counts).
        public static func ignoredLine(rate: Int, tooLong: Int, undecodable: Int) -> String {
            var parts: [String] = []
            if rate > 0 { parts.append("\(rate) from devices sending more than \(perSecond) a second") }
            if tooLong > 0 { parts.append("\(tooLong) longer than \(cap)") }
            if undecodable > 0 { parts.append("\(undecodable) that did not decode") }
            return "Clipboard from devices ignored in a minute: " + (parts.isEmpty ? "none" : parts.joined(separator: ", ")) + "."
        }
    }
}
